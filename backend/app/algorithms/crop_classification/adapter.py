"""GEE crop classification adapter.

Trains a RandomForest on a labeled FeatureCollection (generated by the
"作物时序特征提取" upstream algorithm), evaluates via
``errorMatrix`` (OA / Kappa / confusion matrix), classifies the full ROI,
and exports the result to a GEE Asset. The platform's background poller
then downloads the Asset back into the platform so the operator can
preview / download the GeoTIFF directly.

User-facing flow
---------------
  - GEE Project ID  (ee.Initialize)
  - target year
  - 研究区: 本地上传 / 已上传历史 / GEE Asset ID（三选一）
  - 特征文件: 本地上传 / 已上传历史 / GEE Asset ID（三选一）
  - 固定参数：树数 / DEM 范围 / min_values / max_values / 云量阈值 / 训练比例
    —— 由算法内置，不允许在前端修改（在表单里以只读 notice 形式展示）
  - 高级参数：任务名称 / num_trees / train_ratio / label_property / cloud_pct_max

Result (job.result) shape mirrors ``crop_features`` Pattern B:

    {
      "status": "submitted" → "completed",
      "result_type": "gee_task" → "raster",
      "files": [
        {"name": "<description>_part01.tif", "label": "classification",
         "group": "classification", ...},
        {"name": "<description>_part02.tif", "label": "classification",
         "group": "classification", ...}
      ],
      "metrics": {
        "year": ...,
        "oa": ..., "kappa": ..., "confusion_matrix": [[...], ...],
        "num_trees": ..., "train_ratio": ...,
        "asset_id": ..., "output_tif_name": ...,
        "shard_count": ..., "shard_names": [...],
        "gee_task_id": ...,
        "cards": [{key, label, value, unit}, ...]
      }
    }

The result is cut into several independent GeoTIFFs (see
``configs.DEFAULT_SHARD_COUNT``).  Files that share a ``group`` are shards of
one map: the result page stitches them back together for the preview, while
each shard stays downloadable on its own.
"""
