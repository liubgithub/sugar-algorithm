def run(
    params: Dict[str, Any],
    job_dir: str,
    progress_callback: Optional[ProgressCallback] = None,
) -> Dict[str, Any]:
    """Build the feature stack, train RandomForest, evaluate, classify, export.

    Pattern B: returns ``status="submitted"`` immediately after submitting
    the GEE Export. The GEE poller in ``job_service`` will detect GEE
    COMPLETED and dispatch to :func:`finalize` to wait for the Asset and
    download the GeoTIFF.
    """
    # ----- 1. GEE init -----
    project = (
        params.get("gee_project_id")
        or params.get("gee_project")
        or os.environ.get("EE_PROJECT")
    )
    if not project:
        # 不再兜底到某个历史项目：静默用一个用户没选过的项目发起 GEE 请求，
        # 正是「报错里出现一个我没填过的项目名」这类问题的来源；宁可明确失败。
        return make_result(
            status="failed",
            result_type="json",
            message=(
                "缺少 GEE 项目 ID：请在『GEE 项目 ID』字段填写，"
                "或设置环境变量 EE_PROJECT。"
            ),
        )
    try:
        initialize_ee(project)
    except GeeAuthRequired as exc:
        return make_result(status="failed", result_type="json", message=str(exc))

    if progress_callback:
        progress_callback(5, "正在连接 GEE")

    # ----- 2. 参数解析 -----
    if "year" not in params or params["year"] in ("", None):
        return make_result(
            status="failed",
            result_type="json",
            message="缺少必填参数：年份（year）。",
        )
    try:
        year = int(params["year"])
    except (TypeError, ValueError):
        return make_result(
            status="failed",
            result_type="json",
            message=f"年份必须是整数：{params['year']!r}",
        )

    num_trees = int(params.get("num_trees", cfg.NUM_TREES))
    train_ratio = float(params.get("train_ratio", cfg.TRAIN_RATIO))
    if not (0.0 < train_ratio < 1.0):
        return make_result(
            status="failed",
            result_type="json",
            message=f"训练集比例必须介于 (0, 1) 之间：{train_ratio}",
        )
    label_property = str(params.get("label_property", cfg.LABEL_PROPERTY)) or cfg.LABEL_PROPERTY
    cloud_pct_max = int(params.get("cloud_pct_max", cfg.CLOUD_PCT_MAX))
    if not (0 <= cloud_pct_max <= 100):
        return make_result(
            status="failed",
            result_type="json",
            message=f"Sentinel-2 最大云量必须在 0~100 之间：{cloud_pct_max}",
        )
    # 结果分片数：切成 N 个独立的 GeoTIFF，拼接起来才是完整结果。
    # 见 cfg.DEFAULT_SHARD_COUNT 的说明。
    try:
        shard_count = int(params.get("shard_count", cfg.DEFAULT_SHARD_COUNT))
    except (TypeError, ValueError):
        shard_count = cfg.DEFAULT_SHARD_COUNT
    if shard_count < 1:
        return make_result(
            status="failed",
            result_type="json",
            message=f"结果分片数必须 ≥ 1：{shard_count}",
        )

    # ----- 3. 研究区解析（asset / 本地 / 历史文件） -----
    try:
        roi_asset_ids = _ingest_local(
            local_path=params.get("roi_local_path"),
            asset_id=(params.get("roi_asset_id") or "").strip() or None,
            slot=_ROI_SLOT,
            project=project,
            progress_callback=progress_callback,
            progress_tick=10,
            progress_tick_done=20,
            label="研究区",
        )
    except GeeAuthRequired as exc:
        return make_result(status="failed", result_type="json", message=str(exc))
    except RuntimeError as exc:
        return make_result(status="failed", result_type="json", message=str(exc))
    except Exception as exc:  # noqa: BLE001
        return make_result(
            status="failed",
            result_type="json",
            message=f"研究区处理失败：{exc}",
        )

    # ----- 4. 样本特征文件解析（asset / 本地 / 历史文件） -----
    try:
        samples_asset_ids = _ingest_local(
            local_path=params.get("samples_local_path"),
            asset_id=(params.get("samples_asset_id") or "").strip() or None,
            slot=_SAMPLES_SLOT,
            project=project,
            progress_callback=progress_callback,
            progress_tick=25,
            progress_tick_done=35,
            label="特征文件",
        )
    except GeeAuthRequired as exc:
        return make_result(status="failed", result_type="json", message=str(exc))
    except RuntimeError as exc:
        return make_result(status="failed", result_type="json", message=str(exc))
    except Exception as exc:  # noqa: BLE001
        return make_result(
            status="failed",
            result_type="json",
            message=f"特征文件处理失败：{exc}",
        )

    if not roi_asset_ids:
        return make_result(
            status="failed",
            result_type="json",
            message=(
                "缺少研究区：请上传本地研究区文件（基本参数区『研究区文件』），"
                "或在下方直接填写 GEE 研究区 Asset ID。"
            ),
        )
    if not samples_asset_ids:
        return make_result(
            status="failed",
            result_type="json",
            message=(
                "缺少特征文件：请上传本地特征文件（基本参数区『特征文件』），"
                "或在下方直接填写 GEE 特征文件 Asset ID。"
                "特征文件应由前面的「特征生成算法」生成。"
            ),
        )

    # chunked 上传会返回多个 asset id；用 flatten() 服务端一次性合并。
    # 注意必须走 ingest_service.fc_from_asset_ids —— 直接
    # ee.FeatureCollection(<list[str]>) 是 JS 写法，在 Python API 里会把
    # 资产 id 当几何解析并抛 "Invalid GeoJSON geometry."。
    roi = ingest_service.fc_from_asset_ids(roi_asset_ids)
    roi_bounds = roi.geometry()

    # ----- 5. 构建 12 月时序特征 + DEM -----
    if progress_callback:
        progress_callback(40, "正在构建 12 月 Sentinel-1/2 时序特征 + DEM")

    final_image = _build_time_series_stack(
        year, roi_bounds, cloud_pct_max=cloud_pct_max
    )

    # ----- 5.b 样本点预处理：防御性类型转换 + 清洗 -----
    sample_points = ingest_service.fc_from_asset_ids(samples_asset_ids)

    # 源样本 FC（用户上传的 CSV/GeoJSON，或 crop_features 生成的产物）中
    # class 列常常是 String（"10"），甚至单 FC 内 Integer 与 String 混存。
    # 下游 ee.Classifier.smileRandomForest 会报
    #   "Property 'class' ... Expected type: Float. Actual type: String"
    # reduceColumns / errorMatrix 会报
    #   "Cannot compare values '0' (Integer) and '10' (String)"
    # 这里统一走 ee.String -> ee.Number.parse(..., 10) 把 label_property
    # 转成数值（数值/字符串都能稳定 parse，NaN 走过滤），并剔除转换失败
    # 的行（class 缺失 / NaN / 负值）。源 FC 完全不含 label_property 列时
    # 不过滤，交给下面的 n_samples==0 检查抛清晰的中文错误。
    sample_points = sample_points.map(
        lambda f: _coerce_label_to_number(f, label_property)
    )
    sample_points = sample_points.filter(ee.Filter.notNull([label_property]))
    sample_points = sample_points.filter(ee.Filter.gte(label_property, 0))

    if progress_callback:
        progress_callback(55, "正在校验样本点 label_property 类型")

    n_samples = sample_points.size().getInfo()
    if not n_samples:
        return make_result(
            status="failed",
            result_type="json",
            message=(
                f"样本点 FeatureCollection 中没有任何有效样本（label_property="
                f"'{label_property}' 缺失或全部为无效数值）。"
                f"请检查上传的样本文件：是否包含 {label_property} 列、"
                f"值是否为有效数字（≥ 0）。原始 Asset：{samples_asset_ids}"
            ),
        )

    feature_bands = final_image.bandNames()

    # ----- 6. 训练 + 验证 -----
    if progress_callback:
        progress_callback(60, f"正在按 {train_ratio:.0%} 划分训练/验证集")

    sample_with_random = sample_points.randomColumn("random")
    training_set = sample_with_random.filter(ee.Filter.lt("random", train_ratio))
    validation_set = sample_with_random.filter(ee.Filter.gte("random", train_ratio))

    if progress_callback:
        progress_callback(
            70, f"正在训练 RandomForest（{num_trees} 棵）并计算混淆矩阵"
        )

    rf_model = ee.Classifier.smileRandomForest(num_trees).train(
        features=training_set,
        classProperty=label_property,
        inputProperties=feature_bands,
    )

    # `getInfo()` of every accuracy number + the confusion matrix so the
    # run() result can ship the small metrics to the UI immediately,
    # without waiting for the toAsset export to land. The same logic as
    # the original standalone script.
    error_matrix = (
        validation_set.classify(rf_model).errorMatrix(label_property, "classification")
    )
    matrix_list = error_matrix.getInfo()
    oa = error_matrix.accuracy().getInfo()
    kappa = error_matrix.kappa().getInfo()

    if progress_callback:
        progress_callback(
            80,
            f"精度评估完成：OA={oa:.4f}，Kappa={kappa:.4f}",
        )

    # ----- 7. 全图分类 + 提交 Export.image.toAsset -----
    if progress_callback:
        progress_callback(85, "正在对全图进行分类并提交 Export.image.toAsset")

    classified = final_image.select(feature_bands).classify(rf_model)

    user_task_name = (
        params.get("task_name") or ""
    ).strip() or f"{cfg.DEFAULT_TASK_PREFIX}_{year}"
    # 时间戳后缀防止 GEE 端 description 冲突（用户在同一年内可能多次提交）。
    unique_description = f"{user_task_name}_{time.strftime('%Y%m%d%H%M%S')}"
    asset_id = f"projects/{project}/assets/{unique_description}"
    output_tif_name = f"{unique_description}.tif"

    task = ee.batch.Export.image.toAsset(
        image=classified.toByte(),
        description=unique_description,
        assetId=asset_id,
        scale=cfg.EXPORT_SCALE,
        crs=cfg.EXPORT_CRS,
        maxPixels=cfg.EXPORT_MAX_PIXELS,
        region=roi.geometry(),
    )
    task.start()
    gee_task_id = getattr(task, "id", None) or task.status().get("id")

    if progress_callback:
        progress_callback(
            95,
            f"已提交 GEE：asset={asset_id}；等待后台 finalize 下载",
        )

    # ----- 8. 返回 submitted（Pattern B） -----
    cards = [
        make_card("task_status", "任务状态", "已提交 GEE", ""),
        make_card("year", "目标年份", year, "年"),
        make_card("overall_accuracy", "总体精度 (OA)", round(oa, 4), ""),
        make_card("kappa", "Kappa 系数", round(kappa, 4), ""),
        make_card("num_trees", "RandomForest 树数", num_trees, ""),
        make_card("train_ratio", "训练集比例", f"{train_ratio:.0%}", ""),
        make_card("gee_task_id", "GEE 任务 ID", gee_task_id or "", ""),
        make_card("asset_id", "GEE 资产", asset_id, ""),
        make_card("output_tif", "输出文件", output_tif_name, ""),
    ]

    return make_result(
        status="submitted",
        result_type="gee_task",
        gee_task_id=gee_task_id,
        progress=10,
        metrics={
            "year": year,
            "oa": oa,
            "kappa": kappa,
            "confusion_matrix": matrix_list,
            "num_trees": num_trees,
            "train_ratio": train_ratio,
            "label_property": label_property,
            "cloud_pct_max": cloud_pct_max,
            "shard_count": shard_count,
            "asset_id": asset_id,
            "description": unique_description,
            "output_tif_name": output_tif_name,
            "roi_asset_id": roi_asset_ids[0] if roi_asset_ids else None,
            "roi_asset_ids": list(roi_asset_ids),
            "samples_asset_id": samples_asset_ids[0] if samples_asset_ids else None,
            "samples_asset_ids": list(samples_asset_ids),
            "task_name": user_task_name,
            "cards": cards,
        },
        message=(
            f"GEE 作物分类任务已提交（task_id={gee_task_id}）；"
            f"年份={year}，OA={oa:.4f}，Kappa={kappa:.4f}，"
            f"输出 Asset={asset_id}。"
            f"等待 GEE 端处理完成后由后台自动下载 GeoTIFF。"
        ),
    )


def finalize(
    job: Dict[str, Any],
    job_dir: str,
    progress_callback: Optional[ProgressCallback] = None,
) -> Optional[Dict[str, Any]]:
    """Background finalizer invoked by the GEE poller.

    Steps:
      1. Read ``asset_id`` / ``description`` / ``output_tif_name`` from
         ``job.result.metrics``. Bail with ``None`` if missing.
      2. Wait until the GEE Asset is queryable, up to
         ``_FINALIZE_WAIT_TIMEOUT`` (30 minutes).
      3. Download the Asset as GeoTIFF into ``job_dir/<output_tif_name>``
         via ``geemap.ee_export_image``.
      4. Build and return the new ``make_result`` payload; the poller
         writes it to the job store.

    Raises on any failure so the poller can mark the job as ``failed``
    and surface the error message in the UI.
    """
    result = (job or {}).get("result") or {}
    metrics = result.get("metrics") or {}
    asset_id = metrics.get("asset_id")
    description = metrics.get("description")
    output_tif_name = (
        metrics.get("output_tif_name")
        or (f"{description}.tif" if description else None)
        or "crop_classification.tif"
    )
    if not asset_id or not description:
        return None

    # ----- 0. 把 EE 切回本任务自己的项目（必须在任何 GEE 调用之前）-----
    # ee 的项目绑定是**进程全局**的，一个 FastAPI 进程里所有算法共享。finalize
    # 由后台轮询线程触发，往往在提交本任务的 run() 结束很久之后才跑，这期间
    # 别的算法 / 别的 job 已经把绑定改成了它们的项目。不在这里显式切回来，下面
    # 的 getAsset / geemap 下载就会带着别人的项目号发出去，用户在界面上看到
    # 的是 "Caller does not have required permission to use project <别的项目>"
    # —— 一个和他自己填的项目毫无关系的名字。
    project = project_for_job(job)
    if not project:
        raise RuntimeError(
            "无法从任务参数或结果中解析出该任务的 GEE 项目 ID，"
            f"拒绝在未知项目下访问 GEE。asset={asset_id}"
        )
    initialize_ee(project)  # 失败时抛 GeeAuthRequired，由 job_service 翻译成中文

    # 重新拿一次 roi_asset_ids 用于下载 region；job.params 可能已被清理，
    # 但 metrics 里已经留了。优先读新格式 (List[str])，回退到旧格式 (str)。
    roi_asset_ids_finalize = metrics.get("roi_asset_ids")
    if not roi_asset_ids_finalize:
        legacy = metrics.get("roi_asset_id") or ""
        roi_asset_ids_finalize = [legacy] if legacy else []
    if not roi_asset_ids_finalize:
        # 没有 region 时退化为输出 asset 整张图的几何范围
        try:
            roi = ee.FeatureCollection(asset_id)
            region = roi.geometry()
        except Exception:
            region = None
    else:
        try:
            roi = ingest_service.fc_from_asset_ids(roi_asset_ids_finalize)
            region = roi.geometry()
        except Exception:
            region = None

    if progress_callback:
        progress_callback(50, f"等待 GEE Asset 就绪：{asset_id}")

    # Block here is OK — finalize runs in the GEE poller thread, not an
    # HTTP handler. _FINALIZE_WAIT_TIMEOUT (30 min) gives even large
    # tasks room to finish.
    try:
        _wait_for_asset(asset_id, timeout=_FINALIZE_WAIT_TIMEOUT)
    except TimeoutError as exc:
        # 抛出而非返回 failed —— poller 会把 status 翻成 failed 并把 message
        # 写到 job.message，让前端能看到 GEE 任务还在跑、不当成功对待。
        raise

    if progress_callback:
        progress_callback(90, "下载分类结果 GeoTIFF 到本地")

    local_tif_path = os.path.abspath(os.path.join(job_dir, output_tif_name))
    if region is None:
        # 兜底：不带 region 下载（geemap 会用整张图的 footprint）。
        _download_asset_to_local(
            asset_id,
            local_path=local_tif_path,
            scale=cfg.EXPORT_SCALE,
            crs=cfg.EXPORT_CRS,
            region=None,  # type: ignore[arg-type]
        )
    else:
        _download_asset_to_local(
            asset_id,
            local_path=local_tif_path,
            scale=cfg.EXPORT_SCALE,
            crs=cfg.EXPORT_CRS,
            region=region,
        )

    if not os.path.isfile(local_tif_path):
        raise RuntimeError(
            f"GEE 资产下载完成但未找到本地文件：{local_tif_path}。"
            f"请检查 geemap.ee_export_image 输出目录配置。"
        )

    # 写入分类元数据 sidecar —— preview_service 会读这个文件把
    # 10→甘蔗 / 20→水稻 / 30→桉树 / 40→其他作物 / 50→背景 这样的中文标签
    # 暴露到前端图例，而不是只显示“类别 10/20/...”。失败 best-effort：
    # 写不出来也不应该让整次任务失败。
    #
    # 分片模式下每个分片都要有自己的 sidecar（拼接时逐个读取、合并）。
    shard_count = int(metrics.get("shard_count") or 1)
    file_entries: List[Dict[str, Any]] = []
    shard_names: List[str] = []

    if shard_count > 1:
        # 切成若干独立的 GeoTIFF。它们各自是一个完整的栅格文件，但只有
        # 拼起来才是完整地图 —— 与算法在本地运行时的产物形态一致。
        # 前端按 files[].group 把同一组的分片拼成一张图展示。
        if progress_callback:
            progress_callback(95, f"正在把分类结果切成 {shard_count} 个分片")
        try:
            shards = split_raster_into_shards(
                local_tif_path,
                out_dir=job_dir,
                base_name=os.path.splitext(output_tif_name)[0],
                num_shards=shard_count,
                remove_source=True,
            )
        except Exception as exc:  # noqa: BLE001
            raise RuntimeError(f"分类结果分片失败：{exc}") from exc

        for shard in shards:
            _write_class_sidecar(job_dir, shard["name"])
            shard_names.append(shard["name"])
            file_entries.append(
                {
                    "name": shard["name"],
                    "label": "classification",
                    # 同一个 group 的文件会被拼成一张图
                    "group": "classification",
                    "path": shard["path"],
                    "size_bytes": shard["size_bytes"],
                }
            )
    else:
        _write_class_sidecar(job_dir, output_tif_name)
        shard_names.append(output_tif_name)
        file_entries.append(
            {
                "name": output_tif_name,
                "label": "classification",
                "path": local_tif_path,
                "size_bytes": os.path.getsize(local_tif_path),
            }
        )

    size_bytes = sum(int(f.get("size_bytes") or 0) for f in file_entries)

    if progress_callback:
        progress_callback(100, "GEE 作物分类完成")

    # 保留 run() 里拿到的指标 + 加 output 信息 + 重新生成 cards。
    new_cards = [
        make_card("task_status", "任务状态", "完成", ""),
        make_card("year", "目标年份", metrics.get("year", ""), "年"),
        make_card(
            "overall_accuracy",
            "总体精度 (OA)",
            round(metrics.get("oa", 0) or 0, 4),
            "",
        ),
        make_card(
            "kappa", "Kappa 系数", round(metrics.get("kappa", 0) or 0, 4), ""
        ),
        make_card("num_trees", "RandomForest 树数", metrics.get("num_trees", ""), ""),
        make_card(
            "train_ratio",
            "训练集比例",
            f"{(metrics.get('train_ratio') or 0):.0%}" if metrics.get("train_ratio") is not None else "",
            "",
        ),
        make_card(
            "gee_task_id", "GEE 任务 ID", metrics.get("gee_task_id", "") or "", ""
        ),
        make_card("asset_id", "GEE 资产", asset_id, ""),
        make_card("output_tif", "输出文件", output_tif_name, ""),
    ]

    return make_result(
        status="completed",
        result_type="raster",
        files=file_entries,
        metrics={
            **metrics,
            "output_tif": output_tif_name,
            "shard_names": shard_names,
            "shard_count": len(shard_names),
            "cards": new_cards,
        },
        message=(
            f"GEE 作物分类完成（task_id={metrics.get('gee_task_id', '')}，"
            f"asset={asset_id}，年份={metrics.get('year', '')}，"
            f"OA={metrics.get('oa', 0):.4f}，Kappa={metrics.get('kappa', 0):.4f}，"
            f"输出 {len(shard_names)} 个分片：{'、'.join(shard_names)}，"
            f"合计 {size_bytes} B）"
        ),
    )


