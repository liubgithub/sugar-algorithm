def _coerce_label_to_number(feature: ee.Feature, prop: str) -> ee.Feature:
    """Defensive: coerce a sample's ``label_property`` to ``ee.Number``.

    The upstream sample FC (whether uploaded by the user as a CSV / GeoJSON
    or generated by ``crop_features``) may carry the class label with mixed
    types — some rows as Integer ``0`` and others as String ``"10"`` —
    because ``Export.table.toAsset`` preserves the source schema column-by-
    column, and a CSV imported as String stays String even when every cell
    looks numeric. Two distinct GEE crashes come out of this::

        Property 'class' of feature '00000000000000000000': Invalid type.
        Expected type: Float. Actual type: String. Actual value: 10

        Collection.reduceColumns: Cannot compare values '0' (Type:Integer)
        and '10' (Type:String).

    The reliable server-side coercion is to route the property through
    ``ee.String(raw)`` then ``ee.Number.parse(input, radix=10)`` regardless
    of its starting type::

        - Number 0    -> ee.String("0")    -> ee.Number.parse -> 0
        - String "10" -> ee.String("10")   -> ee.Number.parse -> 10
        - null / unparseable -> Number(NaN) -> filtered out later

    ``ee.Number(value)`` directly is unreliable: the Python wrapper raises
    for non-Number inputs and on the server side does NOT uniformly coerce
    String→Number across all GEE versions, which is what surfaces as the
    second error above when a single FC mixes Integer rows with String rows.

    Combined with the ``filter(ee.Filter.notNull(...) + gte(prop, 0))``
    below, this normalises the labels while dropping truly broken rows
    instead of failing the whole job.

    If the source FC does NOT have ``prop`` at all (user uploaded a
    longitude/latitude-only CSV by mistake), the feature is passed through
    unchanged — the ``notNull`` / ``gte`` filter then drops it, and the
    ``n_samples == 0`` guard surfaces a clear Chinese error.
    """
    has_prop = feature.propertyNames().contains(ee.String(prop))
    raw = feature.get(prop)
    return feature.set(
        prop,
        ee.Algorithms.If(
            has_prop,
            ee.Number.parse(ee.String(raw), 10),
            raw,
        ),
    )


def _mask_s2_clouds(image: ee.Image) -> ee.Image:
    """S2 SR cloud mask via QA60 bits 10/11, then scale reflectance.

    Identical to the original standalone script (and to
    ``crop_features.algorithm._mask_s2_clouds``) — kept inline so this
    module remains importable without pulling the feature-extraction
    module's transitive GEE setup.
    """
    qa = image.select("QA60")
    mask = qa.bitwiseAnd(1 << 10).eq(0).And(qa.bitwiseAnd(1 << 11).eq(0))
    return image.updateMask(mask).divide(10000)


def _build_normalize_fn() -> Any:
    """Return a server-side function that maps each band to [0, 1] via min/max.

    Returns a closure because GEE server-side objects (ee.Image.constant)
    can only be created once and reused across calls. Matches the user's
    original ``normalizeDynamic`` definition.
    """
    min_img = ee.Image.constant(cfg.MIN_VALUES).rename(cfg.BAND_NAMES)
    max_img = ee.Image.constant(cfg.MAX_VALUES).rename(cfg.BAND_NAMES)

    def _normalize(img: ee.Image) -> ee.Image:
        return img.subtract(min_img).divide(max_img.subtract(min_img)).clamp(0, 1)

    return _normalize


def _monthly_image(
    m: ee.Number,
    year: int,
    roi_bounds: ee.Geometry,
    normalize: Any,
    cloud_pct_max: int,
) -> ee.Image:
    """Build one month: S2 + S1 → 11 bands → normalized, tagged with 'month'.

    Mirrors ``get_monthly_image`` from the original script verbatim except
    ``cloud_pct_max`` is now a parameter (default unchanged at 80).
    """
    m_int = ee.Number(m)
    start = ee.Date.fromYMD(year, m_int, 1)
    end = start.advance(1, "month")

    s2 = (
        ee.ImageCollection("COPERNICUS/S2_SR_HARMONIZED")
        .filterBounds(roi_bounds)
        .filterDate(start, end)
        .filter(ee.Filter.lt("CLOUDY_PIXEL_PERCENTAGE", cloud_pct_max))
        .map(_mask_s2_clouds)
        .median()
    )

    s1 = (
        ee.ImageCollection("COPERNICUS/S1_GRD")
        .filterBounds(roi_bounds)
        .filterDate(start, end)
        .filter(ee.Filter.listContains("transmitterReceiverPolarisation", "VV"))
        .filter(ee.Filter.listContains("transmitterReceiverPolarisation", "VH"))
        .filter(ee.Filter.eq("instrumentMode", "IW"))
        .select(["VV", "VH"])
        .median()
    )

    combined = (
        s2.select(["B2", "B3", "B4", "B8", "B11", "B12"])
        .addBands(s2.normalizedDifference(["B8", "B4"]).rename("NDVI"))
        .addBands(
            s2.expression(
                "2.5*((B8-B4)/(B8+6*B4-7.5*B2+1))",
                {
                    "B8": s2.select("B8"),
                    "B4": s2.select("B4"),
                    "B2": s2.select("B2"),
                },
            ).rename("EVI")
        )
        .addBands(s2.normalizedDifference(["B3", "B8"]).rename("NDWI"))
        .addBands(s1)
    )
    return normalize(combined).set("month", m_int)


def _build_time_series_stack(
    year: int,
    roi_bounds: ee.Geometry,
    *,
    cloud_pct_max: int = cfg.CLOUD_PCT_MAX,
) -> ee.Image:
    """12-month normalized stack + DEM, identical to the user's script.

    Reproduces the original ``stackedTimeSeries`` plus ``finalImage``
    (with DEM band appended) pipeline so the trained classifier sees the
    same feature space the upstream time-series feature algorithm
    generates.
    """
    normalize = _build_normalize_fn()
    months = ee.List.sequence(1, cfg.TIME_SERIES_MONTHS)

    monthly = ee.ImageCollection(
        months.map(
            lambda m: _monthly_image(m, year, roi_bounds, normalize, cloud_pct_max)
        )
    )
    annual_median = monthly.median()

    def _fill(img: ee.Image) -> ee.Image:
        img = ee.Image(img)
        m_str = ee.Number(img.get("month")).format("%02d")

        def _rename(b: ee.String) -> ee.String:
            return (
                ee.String(cfg.MONTH_BAND_PREFIX)
                .cat(m_str)
                .cat("_")
                .cat(ee.String(b))
            )

        new_names = img.bandNames().map(_rename)
        return img.unmask(annual_median).rename(new_names)

    filled = monthly.map(_fill)

    def _stack(img: ee.Image, prev: ee.Image) -> ee.Image:
        return ee.Image(prev).addBands(img)

    dummy = ee.Image.constant(0).rename("dummy")
    stacked = ee.Image(filled.iterate(_stack, dummy))
    valid = stacked.bandNames().remove("dummy")
    stacked = stacked.select(valid).unmask(cfg.STACK_NODATA)

    dem = (
        ee.Image("NASA/NASADEM_HGT/001")
        .resample("bilinear")
        .reproject(crs="EPSG:4326", scale=cfg.EXPORT_SCALE)
        .clip(roi_bounds)
    )
    elevation_norm = (
        dem.select("elevation")
        .subtract(cfg.DEM_MIN)
        .divide(cfg.DEM_MAX - cfg.DEM_MIN)
        .clamp(0, 1)
        .rename(cfg.DEM_BAND_NAME)
    )
    return stacked.addBands(elevation_norm)


def _wait_for_asset(asset_id: str, *, timeout: float = _ASSET_WAIT_TIMEOUT) -> None:
    """Poll ``ee.data.getAsset`` until the ingested asset becomes queryable.

    Mirrors the same helper in ``crop_features`` / ``harvest``. ``run()``
    blocks here at most 10 minutes; ``finalize()`` bumps the ceiling.
    """
    deadline = time.monotonic() + timeout
    last_err: Optional[Exception] = None
    while time.monotonic() < deadline:
        try:
            ee.data.getAsset(asset_id)
            return
        except Exception as exc:  # noqa: BLE001
            last_err = exc
            # 等待期间没有请求要发出去，让出进程级 GEE 锁，
            # 否则一次导出会把其它 GEE 任务堵在"提交 GEE 任务"。
            with gee_idle():
                time.sleep(_ASSET_WAIT_INTERVAL)
    raise TimeoutError(
        f"GEE 资产导出超时（>{int(timeout)}s）：{asset_id}; last={last_err}"
    )


def _download_asset_to_local(
    asset_id: str,
    *,
    local_path: str,
    scale: int,
    crs: str,
    region: ee.Geometry,
) -> None:
    """Stream a GEE Asset Image to a local GeoTIFF.

    Wraps ``geemap.ee_export_image`` (which handles both the
    ``getDownloadURL`` fast path for small images and the chunked tiling
    path for large ones). Destination directory is created on demand.
    """
    import geemap  # type: ignore

    out_dir = os.path.dirname(os.path.abspath(local_path))
    os.makedirs(out_dir, exist_ok=True)

    geemap.ee_export_image(
        ee_object=ee.Image(asset_id),
        filename=local_path,
        scale=scale,
        crs=crs,
        region=region,
        file_per_band=False,
    )


def _write_class_sidecar(job_dir: str, tif_name: str) -> Optional[str]:
    """Write the ``<tif>.metadata.json`` class-label sidecar next to a raster.

    ``preview_service`` reads this file and exposes the business semantics
    (10=甘蔗 / 20=水稻 / 30=桉树 / 40=其他作物 / 50=背景) on the frontend
    preview legend instead of a bare "类别 10 / 类别 20 …".

    Every shard needs its own sidecar — the mosaic pipeline reads the
    sidecar of each file it stitches and merges them (first one wins).

    Best-effort: a missing sidecar must never fail the whole job.
    """
    sidecar_path = os.path.abspath(
        os.path.join(job_dir, tif_name + cfg.CLASS_METADATA_SUFFIX)
    )
    sidecar_payload = {
        "schema_version": 1,
        "filename": tif_name,
        "class_labels": {str(k): v for k, v in cfg.CLASS_LABELS.items()},
        "class_colors": {str(k): v for k, v in cfg.CLASS_COLORS.items()},
    }
    try:
        with open(sidecar_path, "w", encoding="utf-8") as fh:
            json.dump(sidecar_payload, fh, ensure_ascii=False, indent=2)
    except Exception as exc:  # noqa: BLE001
        print(
            f"[crop_classification] failed to write class metadata sidecar "
            f"({sidecar_path}): {exc}",
            file=sys.stderr,
        )
        return None
    return sidecar_path


def _ingest_local(
    *,
    local_path: Optional[str],
    asset_id: Optional[str],
    slot: str,
    project: str,
    progress_callback: Optional[ProgressCallback] = None,
    progress_tick: Optional[float] = None,
    progress_tick_done: Optional[float] = None,
    label: str,
) -> Optional[List[str]]:
    """Resolve one of the three input modes for an asset-backed parameter.

    Returns one or more GEE asset ids, or ``None`` when neither input was
    provided. A single-element list ``[id]`` means a single Asset; a
    multi-element list means the source file was chunked because GEE's
    ``Export.table.toAsset`` 10 MB cap couldn't fit it in one shot —
    callers must build the FC via
    ``ingest_service.fc_from_asset_ids(ids)`` at use time (NOT
    ``ee.FeatureCollection(ids)``, which is the JS idiom and raises
    "Invalid GeoJSON geometry." in the Python API).

    Precedence:
      1. ``asset_id`` provided → wrap in a one-element list (with one
         ``ee.data.getAsset`` pre-flight check for clear failure messaging).
      2. ``local_path`` provided → auto-ingest via
         ``ingest_service.ensure_asset_for_local`` (idempotent via the
         per-(algorithm, slot) cache) and persist the *first* chunk's id
         to ``job_store`` so the user can re-use it via the front-end
         picker. Known limitation: if the upload was chunked, picking
         this saved asset only loads the first chunk — to get the full
         FC the user should re-submit the same local file (the cache
         returns all chunks).
      3. Neither → return ``None`` (caller emits a precise Chinese error).

    ``label`` is a short user-facing noun ("研究区" / "特征文件") for
    progress messages and error text.
    """
    if asset_id:
        try:
            ee.data.getAsset(asset_id)
        except Exception as exc:  # noqa: BLE001
            # 权限不足会走到这里（ee.Initialize 不做网络往返，认证不匹配
            # 只在第一次真实 API 调用时才暴露）。翻译成 GeeAuthRequired，
            # 让前端弹出"重新认证"提示，而不是让用户误以为 Asset 不存在。
            raise_if_auth_mismatch(exc, project)
            raise RuntimeError(
                f"无法访问 GEE {label} Asset：{asset_id}。"
                f"请确认 Asset 存在、属于当前项目 ({project})，且您有读取权限。"
                f"原始错误：{exc}"
            ) from exc
        if progress_callback:
            pct = progress_tick_done if progress_tick_done is not None else 15
            progress_callback(pct, f"{label}：复用 {asset_id}")
        return [asset_id]

    if local_path:
        if progress_callback and progress_tick is not None:
            progress_callback(progress_tick, f"{label}：注册本地文件到 GEE Asset")
        try:
            resolved_ids = ingest_service.ensure_asset_for_local(
                local_path=str(local_path),
                slot=slot,
                algorithm=_ALGORITHM_ID,
                project=project,
                kind_hint="feature_collection",
            )
        except GeeAuthRequired:
            raise
        except Exception as exc:  # noqa: BLE001
            raise RuntimeError(f"{label}上传到 GEE 失败：{exc}") from exc

        # 自动把刚生成的 Asset ID 持久化到「已保存 GEE Assets」表里，
        # 让用户后续能直接勾选复用，无需再上传本地文件。best-effort：
        # 保存失败不应阻塞算法本身。chunked 上传时只保存第一个 chunk 作为
        # 主入口（picker 后续可扩展为合并多个 chunk）。
        primary_id = resolved_ids[0] if resolved_ids else None
        if primary_id:
            source_name = Path(local_path).name if local_path else ""
            if len(resolved_ids) > 1:
                source_name = (
                    f"{source_name}（已切分为 {len(resolved_ids)} 个 GEE Asset）"
                )
            try:
                job_store.save_gee_asset(
                    asset_id=primary_id,
                    algorithm_id=_ALGORITHM_ID,
                    source_filename=source_name,
                )
            except Exception as exc:  # noqa: BLE001
                print(
                    f"[crop_classification] save_gee_asset failed "
                    f"(asset={primary_id}): {exc}",
                    file=sys.stderr,
                )

        if progress_callback and progress_tick_done is not None:
            progress_callback(progress_tick_done, f"{label}：已注册 {resolved_ids}")
        return resolved_ids

    return None


