"""GEE crop classification (RandomForest on a labeled FeatureCollection).

Trains a smileRandomForest on the time-series + DEM feature stack, evaluates
via ``errorMatrix`` (Overall Accuracy / Kappa / confusion matrix), classifies
the full ROI and ships the result back to the operator as a GeoTIFF.

Pattern B execution
-------------------
``run()`` immediately returns ``status="submitted"`` with the GEE task id
and the small accuracy metrics (OA / Kappa / confusion matrix). The
background GEE poller in ``app.services.job_service`` watches the task
state and dispatches to :func:`finalize` once GEE reports COMPLETED.
``finalize`` waits for the uploaded Asset to be queryable, downloads the
GeoTIFF into ``job_dir`` via ``geemap.ee_export_image`` so the platform's
``ResultRenderer`` can preview / download it directly, then returns
``status="completed"`` with the file reference.

ROI source
----------
Either:
  * ``roi_local_path``: a local vector file (shp zip / geojson / json)
    auto-ingested into a fresh GEE Asset via
    ``ingest_service.ensure_asset_for_local``;
  * ``roi_asset_id``: an existing ``projects/<project>/assets/<name>``
    Asset — skipped upload, used directly;
  * neither.

Sample-feature file source
-------------------------
Either:
  * ``samples_local_path``: a local CSV with ``longitude`` / ``latitude``
    plus the classification target column (``class`` by default) — auto-
    ingested via ``ingest_service``;
  * ``samples_asset_id``: an existing GEE FeatureCollection Asset;
  * neither.

Fixed parameters
----------------
BAND_NAMES / MIN_VALUES / MAX_VALUES / DEM_MIN / DEM_MAX / CLOUD_PCT_MAX /
NUM_TREES / TRAIN_RATIO / LABEL_PROPERTY live in ``configs.py`` and are
not user-editable on the form. ``num_trees``, ``train_ratio`` and
``label_property`` are surfaced in the collapsed "其他参数" section for
advanced users but default to the hard-coded values.
"""
